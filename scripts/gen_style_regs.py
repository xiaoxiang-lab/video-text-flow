def main() -> None:
    for s in STYLES:
        sid = s["id"]
        ref_dir = ROOT / "ref" / sid
        ref_dir.mkdir(parents=True, exist_ok=True)
        # guide.zh.md
        guide = GUIDE_TEMPLATE.format(**s)
        (ref_dir / "guide.zh.md").write_text(guide, encoding="utf-8")
        # master-prompt.zh.txt
        m = s["master"]
        master = MASTER_TEMPLATE.format(
            cn=s["cn"],
            surface=m["surface"], palette=m["palette"],
            components=m["components"], layout=m["layout"],
        )
        (ref_dir / "master-prompt.zh.txt").write_text(master, encoding="utf-8")
        # json
        reg = {
            "schema_version": 1,
            "id": sid,
            "name": s["name"],
            "summary": s["summary"],
            "status": "stable",
            "master_prompt_file": f"ref/{sid}/master-prompt.zh.txt",
            "guide_files": [f"ref/{sid}/guide.zh.md"],
            "reference_files": [f"ref/style-assets/style-samples/S{s['num']:02d}-{s['cn']}.jpg"],
            "default_shot_seconds": 4,
        }
        styles_dir = ROOT / "config" / "styles"
        (styles_dir / f"{sid}.json").write_text(
            json.dumps(reg, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        print(f"ok {sid}")

